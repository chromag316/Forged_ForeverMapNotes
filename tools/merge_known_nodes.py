#!/usr/bin/env python3
"""Merge mining and herb nodes from players' SavedVariables into the addon.

Usage:
    python tools/merge_known_nodes.py <SavedVariables file> [more files ...]

Each file is a player's
    WTF/Account/<ACCOUNT>/SavedVariables/Forged_ForeverMapNotes.lua

Nodes not already in Data/KnownNodes.lua (same category and title within
DUPLICATE_RADIUS) are written there as a new batch. The addon imports each
batch once per account, so ship a new addon version after running this.
"""

import argparse
import math
import re
import sys
from pathlib import Path

CATEGORIES = ("mining", "herb")
# Same radius the addon uses to treat two logs as the same node.
DUPLICATE_RADIUS = 0.005
COORD_DECIMALS = 4

ROOT = Path(__file__).resolve().parent.parent
DATA_FILE = ROOT / "Data" / "KnownNodes.lua"

HEADER = """\
-- Generated by tools/merge_known_nodes.py -- do not edit by hand.
-- [batch] = { [mapID] = { { x, y, category, title }, ... } }
local addonName, ns = ...

"""


# Minimal parser for the Lua table literals WoW writes to SavedVariables ------

class LuaParser:
    TOKEN = re.compile(
        r"""
        (?P<ws>\s+|--\[\[.*?\]\]|--[^\n]*)
      | (?P<number>-?(?:0[xX][0-9a-fA-F]+|(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?))
      | (?P<string>"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*')
      | (?P<name>[A-Za-z_][A-Za-z0-9_]*)
      | (?P<op>[{}\[\]=,;])
        """,
        re.VERBOSE | re.DOTALL,
    )
    ESCAPES = {"n": "\n", "t": "\t", "r": "\r", "\\": "\\", '"': '"', "'": "'", "\n": "\n"}

    def __init__(self, text):
        self.tokens = []
        pos = 0
        while pos < len(text):
            m = self.TOKEN.match(text, pos)
            if not m:
                raise ValueError(f"unexpected character {text[pos]!r} at offset {pos}")
            pos = m.end()
            if m.lastgroup != "ws":
                self.tokens.append((m.lastgroup, m.group()))
        self.i = 0

    def peek(self):
        return self.tokens[self.i] if self.i < len(self.tokens) else (None, None)

    def next(self):
        tok = self.peek()
        self.i += 1
        return tok

    def expect(self, value):
        kind, tok = self.next()
        if tok != value:
            raise ValueError(f"expected {value!r}, got {tok!r}")

    def assignments(self):
        """Parses `Name = value` statements; returns {name: value}."""
        result = {}
        while self.peek()[0] is not None:
            kind, name = self.next()
            if kind != "name":
                raise ValueError(f"expected a variable name, got {name!r}")
            self.expect("=")
            result[name] = self.value()
        return result

    def value(self):
        kind, tok = self.next()
        if kind == "number":
            return int(tok, 0) if re.fullmatch(r"-?(0[xX][0-9a-fA-F]+|\d+)", tok) else float(tok)
        if kind == "string":
            return self.unescape(tok[1:-1])
        if kind == "name":
            if tok in ("true", "false"):
                return tok == "true"
            if tok == "nil":
                return None
            raise ValueError(f"unexpected name {tok!r}")
        if tok == "{":
            return self.table()
        raise ValueError(f"unexpected token {tok!r}")

    def table(self):
        result, index = {}, 1
        while True:
            if self.peek()[1] == "}":
                self.next()
                return result
            if self.peek()[1] == "[":
                self.next()
                key = self.value()
                self.expect("]")
                self.expect("=")
                result[key] = self.value()
            elif self.peek()[0] == "name" and self.tokens[self.i + 1][1] == "=":
                key = self.next()[1]
                self.next()
                result[key] = self.value()
            else:
                result[index] = self.value()
                index += 1
            if self.peek()[1] in (",", ";"):
                self.next()

    @classmethod
    def unescape(cls, s):
        out, i = [], 0
        while i < len(s):
            c = s[i]
            if c == "\\" and i + 1 < len(s):
                n = s[i + 1]
                if n.isdigit():
                    digits = re.match(r"\d{1,3}", s[i + 1:]).group()
                    out.append(chr(int(digits)))
                    i += 1 + len(digits)
                    continue
                out.append(cls.ESCAPES.get(n, n))
                i += 2
            else:
                out.append(c)
                i += 1
        return "".join(out)


def as_list(table):
    """Lua array table -> Python list, in index order."""
    return [table[k] for k in sorted(k for k in table if isinstance(k, int))]


# Known nodes -----------------------------------------------------------------

def load_known():
    """Returns {batch: {mapID: [(x, y, category, title), ...]}}."""
    if not DATA_FILE.exists():
        return {}
    text = DATA_FILE.read_text(encoding="utf-8")
    start = text.find("ns.KNOWN_NODES")
    if start < 0:
        raise ValueError(f"{DATA_FILE}: no ns.KNOWN_NODES table")
    data = LuaParser(text[start + len("ns."):]).assignments()["KNOWN_NODES"]
    return {
        batch: {mapID: [tuple(as_list(n)) for n in as_list(nodes)] for mapID, nodes in maps.items()}
        for batch, maps in data.items()
    }


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def write_known(known):
    lines = [HEADER + "ns.KNOWN_NODES = {"]
    for batch in sorted(known):
        lines.append(f"    [{batch}] = {{")
        for mapID in sorted(known[batch]):
            lines.append(f"        [{mapID}] = {{")
            for x, y, category, title in sorted(known[batch][mapID], key=lambda n: (n[2], n[3], n[0], n[1])):
                lines.append(
                    f"            {{ {x:.{COORD_DECIMALS}f}, {y:.{COORD_DECIMALS}f}, "
                    f"{lua_string(category)}, {lua_string(title)} }},"
                )
            lines.append("        },")
        lines.append("    },")
    lines.append("}")
    DATA_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def read_player_nodes(path):
    """Yields (mapID, x, y, category, title) for the player's own gathered nodes."""
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    db = LuaParser(text).assignments().get("ForgedForeverMapNotesDB")
    if not isinstance(db, dict):
        raise ValueError("no ForgedForeverMapNotesDB in file")
    for mapID, notes in (db.get("notes") or {}).items():
        if not isinstance(notes, dict):
            continue
        for note in notes.values():
            if not isinstance(note, dict) or note.get("known"):
                continue  # skip nodes that came from this file in the first place
            category, title = note.get("category"), note.get("title")
            x, y = note.get("x"), note.get("y")
            if category not in CATEGORIES or not title or not isinstance(x, (int, float)) or not isinstance(y, (int, float)):
                continue
            if not (0 <= x <= 1 and 0 <= y <= 1):
                continue
            yield int(mapID), round(x, COORD_DECIMALS), round(y, COORD_DECIMALS), category, title


class NodeIndex:
    """Nodes per (mapID, category, title) for duplicate checks."""

    def __init__(self):
        self.nodes = {}

    def add(self, mapID, x, y, category, title):
        self.nodes.setdefault((mapID, category, title), []).append((x, y))

    def has_near(self, mapID, x, y, category, title):
        return any(
            math.hypot(nx - x, ny - y) <= DUPLICATE_RADIUS
            for nx, ny in self.nodes.get((mapID, category, title), ())
        )


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("files", nargs="+", help="players' Forged_ForeverMapNotes.lua SavedVariables files")
    parser.add_argument("--dry-run", action="store_true", help="report counts without writing Data/KnownNodes.lua")
    args = parser.parse_args()

    known = load_known()
    index = NodeIndex()
    for maps in known.values():
        for mapID, nodes in maps.items():
            for x, y, category, title in nodes:
                index.add(mapID, x, y, category, title)

    batch = {}
    added = 0
    for path in args.files:
        try:
            nodes = list(read_player_nodes(path))
        except (OSError, ValueError) as err:
            print(f"skipped {path}: {err}", file=sys.stderr)
            continue
        new = 0
        for mapID, x, y, category, title in nodes:
            if index.has_near(mapID, x, y, category, title):
                continue
            index.add(mapID, x, y, category, title)
            batch.setdefault(mapID, []).append((x, y, category, title))
            new += 1
        print(f"{path}: {len(nodes)} node(s), {new} new")
        added += new

    if not added:
        print("No new nodes.")
        return
    number = max(known, default=0) + 1
    if args.dry_run:
        print(f"Would add {added} node(s) as batch {number}.")
        return
    known[number] = batch
    write_known(known)
    print(f"Added {added} node(s) as batch {number} to {DATA_FILE.relative_to(ROOT)}.")


if __name__ == "__main__":
    main()
